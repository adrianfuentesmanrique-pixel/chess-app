// Builds js/opening-library.js, the app's built-in opening library. Dev tool, not shipped.
//
//   node tools/build-opening-library.mjs          writes js/opening-library.js
//
// Input: tools/opening-library-src/{a..e}.tsv, the Lichess list of named
// openings (CC0, see SOURCE.md there). No network, no engine: the same input
// always gives the same file, and tests/unit/opening-library.test.js fails if
// the file on disk is not what this tool would write.
//
// What it does to every line:
//  - plays it on a board from the starting position (an illegal line stops the build)
//  - groups it under its opening, the part of the name before the colon
//  - tags it with the app's OWN opening name for those moves: classifyOpening()
//    from js/openings-eco.js. That name is the key the Opening ELO is stored
//    under, so the library never invents or renames one. A line the app cannot
//    name (1.a3, 1.h3 ...) gets no key (-1), exactly as a game played that way.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from '../vendor/chess.js';
import { classifyOpening, VALID_OPENING_NAMES } from '../js/openings-eco.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'tools', 'opening-library-src');
const OUT = path.join(ROOT, 'js', 'opening-library.js');
const SOURCE_COMMIT = 'a6189a30dc273ccb21fc2536a9a2fefd5592a67a';

const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function readRows() {
  const rows = [];
  for (const f of ['a', 'b', 'c', 'd', 'e']) {
    const lines = fs.readFileSync(path.join(SRC, f + '.tsv'), 'utf8').split('\n').slice(1);
    for (const raw of lines) {
      const line = raw.replace('\r', '');
      if (!line) continue;
      const [eco, name, pgn] = line.split('\t');
      if (!eco || !name || !pgn) throw new Error(`bad row in ${f}.tsv: ${line}`);
      rows.push({ eco, name, tokens: pgn.trim().split(' ').filter(t => t && !t.endsWith('.')) });
    }
  }
  return rows;
}

// The line as the app's own board writes it, or an error naming the bad move.
function playLine(row) {
  const game = new Chess();
  const sans = [];
  for (const t of row.tokens) {
    let mv = null;
    try { mv = game.move(t); } catch { mv = null; }
    if (!mv) throw new Error(`illegal move ${t} in "${row.name}" (${row.tokens.join(' ')})`);
    sans.push(mv.san);
  }
  return sans;
}

export function buildLibrary() {
  const groups = new Map();
  const seen = new Set();
  for (const row of readRows()) {
    const sans = playLine(row);
    const cut = row.name.indexOf(': ');
    const group = cut < 0 ? row.name : row.name.slice(0, cut);
    const variation = cut < 0 ? '' : row.name.slice(cut + 2);
    const moves = sans.join(' ');
    const id = row.name + '|' + moves;
    if (seen.has(id)) continue;
    seen.add(id);
    const key = classifyOpening(sans) || null;
    if (key && !VALID_OPENING_NAMES.has(key)) throw new Error(`unknown key ${key}`);
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push({ eco: row.eco, variation, moves, plies: sans.length, key });
  }
  const keys = [...new Set([...groups.values()].flat().map(l => l.key).filter(Boolean))].sort(byText);
  const library = [...groups.keys()].sort(byText).map(name => {
    const lines = groups.get(name).sort((a, b) => byText(a.moves, b.moves) || byText(a.variation, b.variation));
    // Whose opening it is: the colour of the move that earns the name.
    const side = Math.min(...lines.map(l => l.plies)) % 2 === 1 ? 'w' : 'b';
    return { name, side, lines: lines.map(l => [l.eco, l.variation, l.moves, l.key ? keys.indexOf(l.key) : -1]) };
  });
  return { keys, library };
}

export function buildLibrarySource() {
  const { keys, library } = buildLibrary();
  const out = [];
  out.push('// GENERATED by tools/build-opening-library.mjs. Do not edit by hand: change the');
  out.push('// tool or its input and run it again.');
  out.push('//');
  out.push('// The built-in opening library: every named opening and variation of the Lichess');
  out.push(`// list (lichess-org/chess-openings @ ${SOURCE_COMMIT.slice(0, 7)}, CC0), grouped by opening.`);
  out.push('//');
  out.push('// OPENING_LIBRARY: [{ name, side, lines }]');
  out.push("//   name   the opening, in English. A label and a search text, never a storage key.");
  out.push("//   side   'w' or 'b': the colour of the move that earns the name.");
  out.push('//   lines  [eco, variation, moves, key]');
  out.push("//            variation  '' for the opening itself, else the part after the colon");
  out.push('//            moves      SAN, space separated, from the starting position');
  out.push('//            key        index into LIBRARY_KEYS, or -1: the name classifyOpening()');
  out.push('//                       gives these moves, which is the Opening ELO storage key');
  out.push('');
  out.push('export const LIBRARY_SOURCE_COMMIT = ' + JSON.stringify(SOURCE_COMMIT) + ';');
  out.push('');
  out.push('export const LIBRARY_KEYS = [');
  for (const k of keys) out.push('  ' + JSON.stringify(k) + ',');
  out.push('];');
  out.push('');
  out.push('export const OPENING_LIBRARY = [');
  for (const g of library) {
    out.push(`{ name: ${JSON.stringify(g.name)}, side: '${g.side}', lines: [`);
    for (const l of g.lines) out.push(JSON.stringify(l) + ',');
    out.push(']},');
  }
  out.push('];');
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildLibrarySource();
  fs.writeFileSync(OUT, text);
  const { keys, library } = buildLibrary();
  const lines = library.flatMap(g => g.lines);
  const plies = lines.map(l => l[2].split(' ').length);
  console.log(`wrote js/opening-library.js: ${Buffer.byteLength(text)} bytes`);
  console.log(`${library.length} openings, ${lines.length} lines, ${new Set(library.flatMap(g => g.lines.map(l => g.name + ': ' + l[1]))).size} names`);
  console.log(`${keys.length} of the app's ${VALID_OPENING_NAMES.size} names used as keys, ${lines.filter(l => l[3] < 0).length} lines without a key`);
  console.log(`depth in moves: average ${(plies.reduce((a, b) => a + b, 0) / plies.length / 2).toFixed(1)}, longest ${Math.ceil(Math.max(...plies) / 2)}`);
}
